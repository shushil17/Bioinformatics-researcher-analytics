"""Orchestration: Reproduction Agent -> Critic (LLM-as-judge) -> Report -> Human sign-off."""
import json
import platform
import uuid
from datetime import datetime, timezone
from importlib.metadata import version

import pandas as pd

from . import config
from .agent import Agent, complete
from .tools import RunContext

SYSTEM_PROMPT = """You are the Literature-to-Analysis Reproduction Agent for a bioinformatics team.
Goal: given a paper, independently re-run its primary transcriptomic analysis from public data
and report whether the published findings reproduce.

Workflow (adapt if a step fails, but keep this order):
1. resolve_paper, then get_paper_sections if open-access full text exists.
2. BLINDED PRE-REGISTRATION: from the paper text only, extract the genes the authors explicitly
   report as changed in the primary comparison, with direction (max 12), plus the DE gene count
   and FDR they report. Call register_published_claims. This locks the claims before any data
   is seen, so the comparison cannot be biased by the results.
3. Identify the primary GEO series (GSE) the paper analysed. If several, pick the one matching
   the main comparison and say why.
4. get_geo_series. Map the paper's main comparison onto GEO sample characteristics. Choose the
   group field, control value, treatment value (use the EXACT strings from GEO) and, if the
   design is paired (same donor/cell line in both arms), a pair_field. Exclude unrelated arms.
5. Call download_count_matrix directly. The system pauses that call for human approval by
   itself; do not stop to ask for approval. If the tool result says it was declined, stop and report.
6. run_differential_expression with your chosen design.
7. compare_with_published, then write the final report.

Hard rules:
- Every number in your report must come from a tool output. Never estimate or invent values.
- Do not draw new biological conclusions; only assess reproduction.
- Work autonomously through all steps. Do not end your turn to ask the user anything; the run
  ends only with the final report (or an explanation of why you are blocked).
- If blocked (no full text, no GEO series, no count matrix), stop and explain the manual step needed.

Final answer: markdown with these sections:
## Verdict  (one line: the verdict from compare_with_published, plus one-sentence summary)
## What the paper claims
## What the agent did  (dataset, samples used, design and WHY you chose it)
## Results vs. published
## Divergences and likely causes  (classify each as TECHNICAL, e.g. genome build hg19 vs GRCh38,
   aligner/quantifier, normalisation, DE method, thresholds; or POTENTIAL GENUINE DISCREPANCY)
## Recommended human checks
"""

CRITIC_PROMPT = """You are an independent QA reviewer for an AI-generated reproduction report.
Compare the REPORT against the EVIDENCE (raw tool outputs). Flag any number, gene, sample count
or claim in the report that is not supported by the evidence, any overstated conclusion, and any
missing caveat. Reply in markdown:
**QA status:** PASS or NEEDS REVIEW
Then a short bullet list of findings (max 6). Be concise and specific."""


def new_context() -> RunContext:
    run_id = datetime.now().strftime("%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:4]
    run_dir = config.RUNS_DIR / run_id
    run_dir.mkdir(parents=True)
    return RunContext(run_id=run_id, run_dir=run_dir)


def run(identifier: str, on_event=None, approver=None) -> RunContext:
    ctx = new_context()
    agent = Agent(ctx, SYSTEM_PROMPT, on_event=on_event, approver=approver)
    narrative = agent.run(f"Reproduce the primary differential-expression finding of this paper: {identifier}")

    evidence = {k: ctx.state.get(k) for k in ("paper", "claims", "comparison")}
    if "de" in ctx.state:
        evidence["de_params"] = {k: v for k, v in ctx.state["de"]["params"].items() if k != "samples"}
    agent.emit("critic_start")
    critique = complete(f"REPORT:\n{narrative}\n\nEVIDENCE:\n{json.dumps(evidence, default=str)[:30000]}",
                        CRITIC_PROMPT)
    agent.emit("critic", text=critique)

    report = build_report(ctx, narrative, critique)
    (ctx.run_dir / "report.md").write_text(report, encoding="utf-8")
    agent.emit("report", path=str(ctx.run_dir / "report.md"))
    ctx.state["narrative"], ctx.state["critique"], ctx.state["report"] = narrative, critique, report
    return ctx


def build_report(ctx: RunContext, narrative: str, critique: str) -> str:
    p, de, cmp_ = ctx.state.get("paper", {}), ctx.state.get("de"), ctx.state.get("comparison")
    lines = [
        f"# Reproduction Report: {p.get('title', 'Unknown paper')}",
        f"*Run `{ctx.run_id}`, generated {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}. "
        f"**Status: DRAFT, pending human sign-off.***", "",
        narrative, "", "---", "## Evidence (generated by code, not by the LLM)",
    ]
    if cmp_:
        lines += [f"**Deterministic verdict:** {cmp_['verdict']} "
                  f"({cmp_['claims_confirmed']} claims confirmed; rule: {cmp_['verdict_rule']})", "",
                  pd.DataFrame(cmp_["per_gene"]).to_markdown(index=False), "",
                  f"DE genes at reported FDR: ours = {cmp_['our_de_gene_count_at_reported_fdr']}, "
                  f"paper = {cmp_['reported_de_gene_count'] or 'not stated'}", ""]
    lines += ["## Independent QA review (critic model)", critique, "", "## Provenance"]
    geo = next(iter(ctx.state.get("geo", {}).values()), {})
    prov = {
        "Paper": f"PMID {p.get('pmid')} | {p.get('pmcid')} | doi:{p.get('doi')}",
        "Dataset": de["gse"] if de else "n/a",
        "Genome build": geo.get("count_files", {}).get("genome_build", "n/a"),
        "Counts": "NCBI GEO RNA-seq pipeline (HISAT2 + featureCounts)",
        "DE method": de["params"]["method"] if de else "n/a",
        "Design": de["params"]["design"] if de else "n/a",
        "Contrast": f"{de['params']['treatment']} vs {de['params']['control']}" if de else "n/a",
        "Samples": de["params"]["n_samples"] if de else "n/a",
        "Full results": de["csv"].name if de else "n/a",
        "LLM": f"{config.LLM_PROVIDER}: {config.ACTIVE_MODEL} (agent + critic)",
        "Software": f"Python {platform.python_version()}, pydeseq2 {version('pydeseq2')}, "
                    + (f"boto3 {version('boto3')}" if config.LLM_PROVIDER == "bedrock"
                       else f"google-genai {version('google-genai')}"),
        "Audit trail": "trace.jsonl (every thought, tool call, approval, result)",
    }
    lines += [f"- **{k}:** {v}" for k, v in prov.items()]
    if de:
        lines += ["", "### Samples used", pd.DataFrame(de["params"]["samples"]).to_markdown(index=False)]
    return "\n".join(lines)
